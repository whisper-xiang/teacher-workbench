/** 按 id 补齐预置工具，不覆盖用户已有或已改过的同 id 条目。 */
export function mergePresetTools(existing: ToolItem[] | undefined, presets = DEFAULT_TOOLS): ToolItem[] {
  if (!existing?.length) return presets
  const have = new Set(existing.map((item) => item.id))
  const missing = presets.filter((item) => !have.has(item.id))
  return missing.length ? [...existing, ...missing] : existing
}
